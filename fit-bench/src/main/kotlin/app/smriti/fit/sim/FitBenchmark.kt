/** Per-instance outcome of one policy. */
data class Outcome(val config: Config, val eval: Evaluation, val nanos: Long) {
    val anyGeometric get() = eval.geometric.isNotEmpty()
    val severe get() = eval.violations.any { it.kind == ViolationKind.ESSENTIAL_HIDDEN || it.kind == ViolationKind.OVERLAP }
    val anyViolation get() = eval.violations.isNotEmpty()
}

data class Row(val inst: Instance, val b1: Outcome, val b2: Outcome, val fit: Outcome, val decision: Decision)

object Bootstrap {
    /** Paired bootstrap 95% CI of mean(a − b) over instances (2000 resamples, seed 99). */
    fun ci(a: DoubleArray, b: DoubleArray, resamples: Int = 2000, seed: Int = 99): Triple<Double, Double, Double> {
        val d = DoubleArray(a.size) { a[it] - b[it] }
        val r = Random(seed)
        val means = DoubleArray(resamples) { var s = 0.0; repeat(d.size) { s += d[r.nextInt(d.size)] }; s / d.size }.sorted()
        return Triple(d.average(), means[(0.025 * resamples).toInt()], means[(0.975 * resamples).toInt() - 1])
    }
}

private fun f(x: Double, d: Int = 3) = "%.${d}f".format(Locale.ROOT, x)
private fun pct(x: Double) = "%.1f%%".format(Locale.ROOT, 100 * x)

fun run(seeds: LongRange, eval: Boolean, content: Content, solver: FitSolver): List<Row> {
    val layout = solver.layout
    val greedy = GreedyRepair(layout)
    return seeds.map { seed ->
        val inst = Instances.make(seed, content, eval)
        fun timed(block: () -> Config): Outcome {
            val t = System.nanoTime(); val c = block(); val dt = System.nanoTime() - t
            return Outcome(c, layout.evaluate(inst.screen, inst.needs, inst.device, c), dt)
        }
        val b1 = timed { CurrentRules.choose(inst.screen, inst.needs, inst.device) }
        val b2 = timed { greedy.choose(inst.screen, inst.needs, inst.device) }
        var decision: Decision? = null
        val fit = timed { solver.solve(inst.screen, inst.needs, inst.device).also { decision = it }.config }
        Row(inst, b1, b2, fit, decision!!)
    }
}

fun report(title: String, rows: List<Row>, gates: Boolean): String = buildString {
    val n = rows.size
    appendLine("# $title")
    appendLine()
    appendLine("Generated by `fit/src/main/kotlin/app/smriti/fit/sim/FitBenchmark.kt`. Synthetic instances built from real SMRITI strings and the app's bundled Noto fonts; no people, no behavioural data.")
    appendLine()
    appendLine("Instances: **$n** (seeds ${rows.first().inst.seed}–${rows.last().inst.seed}). Real radio screen: ${rows.count { it.inst.realScreen }}; generated activity panels: ${rows.count { !it.inst.realScreen }}.")
    val feasible = rows.filter { it.decision.status == Status.OPTIMAL }
    appendLine()
    appendLine("Solver status: " + Status.entries.joinToString(", ") { s -> "$s ${rows.count { it.decision.status == s }}" } + ". " +
        "An instance is *feasible* when some configuration meets every need (status OPTIMAL): ${feasible.size} (${pct(feasible.size / n.toDouble())}).")
    appendLine()

    fun table(label: String, set: List<Row>) {
        if (set.isEmpty()) return
        appendLine("### $label (n = ${set.size})")
        appendLine()
        appendLine("| Policy | Any geometric violation | Severe (hidden control / overlap) | Any violation incl. text need | Mean text deficit (levels) | Picture kept |")
        appendLine("|---|---|---|---|---|---|")
        val withPic = set.filter { it.inst.screen.panel.hasIllustration }
        for ((name, sel) in listOf<Pair<String, (Row) -> Outcome>>("B1 current rules" to { it.b1 }, "B2 rules + greedy repair" to { it.b2 }, "**Fit solver**" to { it.fit })) {
            val o = set.map(sel)
            appendLine("| $name | ${pct(o.count { it.anyGeometric } / set.size.toDouble())} | ${pct(o.count { it.severe } / set.size.toDouble())} | ${pct(o.count { it.anyViolation } / set.size.toDouble())} | ${f(o.map { it.eval.textDeficit.toDouble() }.average())} | " +
                (if (withPic.isEmpty()) "–" else pct(withPic.count { sel(it).eval.illustrationShown } / withPic.size.toDouble())) + " |")
        }
        appendLine()
    }
    table("All instances", rows)
    table("Feasible instances", feasible)
    table("Infeasible instances (no configuration meets every need)", rows.filter { it.decision.status != Status.OPTIMAL })

    appendLine("### Violations by kind (instances with at least one)")
    appendLine()
    appendLine("| Kind | B1 | B2 | Fit |")
    appendLine("|---|---|---|---|")
    for (k in ViolationKind.entries) {
        fun c(sel: (Row) -> Outcome) = rows.count { r -> sel(r).eval.violations.any { it.kind == k } }
        appendLine("| $k | ${c { it.b1 }} | ${c { it.b2 }} | ${c { it.fit }} |")
    }
    appendLine()

    appendLine("### Paired differences (bootstrap 95% CI, 2000 resamples, seed 99)")
    appendLine()
    appendLine("Positive = Fit better.")
    appendLine()
    appendLine("| Comparison | Metric | Difference | 95% CI |")
    appendLine("|---|---|---|---|")
    fun ind(sel: (Row) -> Boolean) = rows.map { if (sel(it)) 1.0 else 0.0 }.toDoubleArray()
    val ciRows = mutableMapOf<String, Triple<Double, Double, Double>>()
    for ((bn, bsel) in listOf<Pair<String, (Row) -> Outcome>>("B1" to { it.b1 }, "B2" to { it.b2 })) {
        val metrics = listOf<Pair<String, Pair<DoubleArray, DoubleArray>>>(
            "geometric-violation rate" to (ind { bsel(it).anyGeometric } to ind { it.fit.anyGeometric }),
            "severe-violation rate" to (ind { bsel(it).severe } to ind { it.fit.severe }),
            "any-violation rate" to (ind { bsel(it).anyViolation } to ind { it.fit.anyViolation }),
            "text deficit" to (rows.map { bsel(it).eval.textDeficit.toDouble() }.toDoubleArray() to rows.map { it.fit.eval.textDeficit.toDouble() }.toDoubleArray()),
            "picture lost" to (ind { it.inst.screen.panel.hasIllustration && !bsel(it).eval.illustrationShown } to ind { it.inst.screen.panel.hasIllustration && !it.fit.eval.illustrationShown }),
        )
        for ((m, ab) in metrics) {
            val ci = Bootstrap.ci(ab.first, ab.second)
            ciRows["$bn/$m"] = ci
            appendLine("| Fit vs $bn | $m | ${f(ci.first, 4)} | [${f(ci.second, 4)}, ${f(ci.third, 4)}] |")
        }
    }
    appendLine()

    appendLine("### Strata: geometric-violation rate (B1 / B2 / Fit)")
    appendLine()
    appendLine("| Stratum | n | B1 | B2 | Fit | Feasible |")
    appendLine("|---|---|---|---|---|---|")
    val strata = listOf<Pair<String, (Row) -> String>>(
        "language" to { it.inst.needs.language.name },
        "content" to { if (it.inst.realScreen) "real radio screen" else "generated panel" },
        "device" to { it.inst.deviceClass },
        "system font scale" to { f(it.inst.device.systemFontScale, 2) },
        "in-app text" to { it.inst.needs.textLevel.name + if (it.inst.needs.textIsNeed) " (need)" else " (preference)" },
        "min target" to { "${it.inst.needs.minTargetDp} dp" },
    )
    for ((sn, key) in strata) for ((v, g) in rows.groupBy(key).toSortedMap()) {
        fun r(sel: (Row) -> Outcome) = pct(g.count { sel(it).anyGeometric } / g.size.toDouble())
        appendLine("| $sn = $v | ${g.size} | ${r { it.b1 }} | ${r { it.b2 }} | ${r { it.fit }} | ${pct(g.count { it.decision.status == Status.OPTIMAL } / g.size.toDouble())} |")
    }
    appendLine()

    // Explanations: every field changed from the design as drawn should carry a concrete reason.
    val expl = rows.flatMap { r -> r.decision.explanations.filter { it.field !in setOf("status", "motion") } }
    val concrete = expl.count { "would cause" in it.reason || "kept" in it.reason }
    appendLine("### Explanations")
    appendLine()
    appendLine("Changed decisions explained: ${expl.size}; with a concrete counterfactual reason (a named violation, a lock or stability): $concrete (${pct(if (expl.isEmpty()) 1.0 else concrete / expl.size.toDouble())}). The rest are ranked preferences (for example \"also fits but hides the picture\"). B1 and B2 give no explanations.")
    appendLine()

    val t = rows.map { it.fit.nanos / 1e6 }.sorted()
    val t2 = rows.map { it.b2.nanos / 1e6 }.sorted()
    fun q(l: List<Double>, p: Double) = l[((l.size - 1) * p).toInt()]
    appendLine("### Time per screen decision (JVM, this machine, includes the first-call text measurement)")
    appendLine()
    appendLine("Fit: p50 ${f(q(t, 0.5))} ms, p95 ${f(q(t, 0.95))} ms, max ${f(t.last())} ms; candidates evaluated per screen: ${rows.map { it.decision.candidatesEvaluated }.distinct().sorted()}. B2: p50 ${f(q(t2, 0.5))} ms, p95 ${f(q(t2, 0.95))} ms.")
    appendLine()

    if (gates) {
        // Pre-registered in docs/flagship/FIT_PROTOCOL.md (committed before this run).
        val f1 = rows.all { r -> (r.decision.status == Status.OPTIMAL) == r.fit.eval.violations.isEmpty() } &&
            feasible.all { it.fit.eval.violations.isEmpty() }
        val g1 = ciRows.getValue("B1/geometric-violation rate")
        val f2 = g1.second > 0 && g1.first >= 0.05
        val g2 = ciRows.getValue("B2/geometric-violation rate")
        val d2 = ciRows.getValue("B2/text deficit")
        val f3 = g2.third >= 0 && d2.third >= 0
        val f4 = q(t, 0.95) <= 20.0
        appendLine("## Pre-registered gates (FIT_PROTOCOL_v2.md)")
        appendLine()
        appendLine("| Gate | Requirement | Result |")
        appendLine("|---|---|---|")
        appendLine("| F1 correctness | No violation whenever a feasible configuration exists; status OPTIMAL exactly on feasible instances | ${if (f1) "PASS" else "FAIL"} |")
        appendLine("| F2 vs current rules | Geometric-violation rate lower than B1: CI lower bound > 0 and reduction ≥ 5 points | ${if (f2) "PASS" else "FAIL"} (${f(g1.first, 4)} [${f(g1.second, 4)}, ${f(g1.third, 4)}]) |")
        appendLine("| F3 not worse than greedy repair | Geometric-violation rate and text deficit vs B2: CI upper bound ≥ 0 (not significantly worse) | ${if (f3) "PASS" else "FAIL"} (violations ${f(g2.first, 4)} [${f(g2.second, 4)}, ${f(g2.third, 4)}]; deficit ${f(d2.first, 4)} [${f(d2.second, 4)}, ${f(d2.third, 4)}]) |")
        appendLine("| F4 latency | p95 time per screen decision ≤ 20 ms (JVM) | ${if (f4) "PASS" else "FAIL"} (${f(q(t, 0.95))} ms) |")
        appendLine()
        val strictly = g2.second > 0 || d2.second > 0
        appendLine("**Verdict: ${if (f1 && f2 && f3 && f4) "GO" else "NO-GO"}.** Strictly better than B2 on at least one metric (CI lower bound > 0): ${if (strictly) "yes" else "no"}.")
        appendLine()
        appendLine("F5 (model validity against real Compose rendering) is reported separately in FIT_VALIDATION_v2.md.")
    }
}

private fun demo(content: Content, solver: FitSolver): String = buildString {
    appendLine("# SMRITI Fit demo: the radio screen under different explicit needs")
    appendLine()
    appendLine("Generated by `./gradlew :fit:runFitDemo`. Same screen and strings; the only differences are the device and the settings a person or caregiver chose.")
    appendLine()
    val cases = listOf(
        Triple("Default settings, Tamil, phone 360×800", Needs(), Device(360, 800)),
        Triple("Tamil, LARGER text as a need, 64 dp targets, phone 360×800", Needs(textLevel = TextLevel.LARGER, textIsNeed = true, minTargetDp = 64), Device(360, 800)),
        Triple("Tamil, default settings, phone in landscape 800×360", Needs(), Device(800, 360)),
        Triple("Tamil, system font 1.3 + LARGER (preference), phone in landscape 800×360", Needs(textLevel = TextLevel.LARGER), Device(800, 360, 1.3)),
        Triple("English, system font 2.0 + LARGER as a need, small phone 320×568", Needs(language = Lang.ENGLISH, textLevel = TextLevel.LARGER, textIsNeed = true), Device(320, 568, 2.0)),
    )
    val greedy = GreedyRepair(solver.layout)
    for ((label, needs, device) in cases) {
        val screen = content.radio(needs.language)
        appendLine("## $label")
        appendLine()
        for ((name, cfg) in listOf("B1 current rules" to CurrentRules.choose(screen, needs, device), "B2 greedy repair" to greedy.choose(screen, needs, device))) {
            val e = solver.layout.evaluate(screen, needs, device, cfg)
            appendLine("- **$name**: ${cfg.short()} → " + (if (e.violations.isEmpty()) "no violations" else e.violations.joinToString("; ") { "${it.kind} ${it.where} (${it.detail})" }))
        }
        val d = solver.solve(screen, needs, device)
        appendLine("- **Fit** [${d.status}]: ${d.config.short()} → " + (if (d.violations.isEmpty()) "no violations" else d.violations.joinToString("; ") { "${it.kind} ${it.where} (${it.detail})" }))
        for (x in d.explanations) appendLine("  - ${x.field} = ${x.chosen}: ${x.reason}")
        appendLine()
    }
    appendLine("## A lock: the caregiver keeps two buttons per row (Tamil, LARGER need, 360×800)")
    appendLine()
    val needs = Needs(textLevel = TextLevel.LARGER, textIsNeed = true)
    val d = solver.solve(content.radio(Lang.TAMIL), needs, Device(360, 800), Locks(columns = 2))
    appendLine("- **Fit** [${d.status}]: ${d.config.short()} → " + (if (d.violations.isEmpty()) "no violations" else d.violations.joinToString("; ") { "${it.kind} ${it.where}" }))
    for (x in d.explanations) appendLine("  - ${x.field} = ${x.chosen}: ${x.reason}")
}

private fun Config.short() = "top bar $hudRows row(s)${if (hudFollowsTextSize) ", follows text size" else ", system-size labels"}; $columns column(s), $style, picture ${if (illustration) "on" else "off"}, text $textLevel"

fun main(args: Array<String>) {
    val (mode, res, out) = args
    val resDir = File(res)
    val content = Content(resDir)
    val solver = FitSolver(CachingMeasurer(AwtMeasurer(resDir)))
    val text = when (mode) {
        "dev" -> report("SMRITI Fit v2: development results (seeds 1–2000, development content pool)", run(Instances.DEV_SEEDS, false, content, solver), gates = false)
        "eval" -> report("SMRITI Fit v2: pre-registered evaluation (seeds 10001–15000, held-out content pool)", run(Instances.EVAL_SEEDS, true, content, solver), gates = true)
        "demo" -> demo(content, solver)
        // Development only: concrete violating instances per device class, for checking the model.
        "examples" -> buildString {
            for ((cls, g) in run(Instances.DEV_SEEDS, false, content, solver).groupBy { it.inst.deviceClass }.toSortedMap()) {
                appendLine("## $cls")
                for (r in g.filter { it.b1.anyGeometric }.take(6)) {
                    appendLine("- seed ${r.inst.seed} ${r.inst.screen.id} ${r.inst.needs.language} ${r.inst.device} ${r.inst.needs.textLevel}: " +
                        r.b1.eval.geometric.joinToString("; ") { "${it.kind} ${it.where} ${it.detail}" })
                    if (r.fit.anyGeometric) appendLine("  - Fit ${r.decision.status}: " + r.fit.eval.violations.joinToString("; ") { "${it.kind} ${it.where} ${it.detail}" })
                }
            }
        }
        else -> error("mode: dev | eval | demo")
    }
    File(out).apply { parentFile.mkdirs() }.writeText(text)
    println(text)
}
