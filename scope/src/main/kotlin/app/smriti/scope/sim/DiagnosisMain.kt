package app.smriti.scope.sim

import app.smriti.scope.ContextSnapshot
import app.smriti.scope.ExplicitPreferenceResponse
import app.smriti.scope.ModelConfig
import app.smriti.scope.PairwisePreferenceEvent
import app.smriti.scope.ScopeEngine
import app.smriti.scope.SocialMode
import app.smriti.scope.normalCdf
import app.smriti.scope.sigmoid
import java.io.File
import java.util.Locale
import kotlin.math.PI
import kotlin.math.sqrt

/**
 * Diagnoses why the v1 gate (ScopeEngine.recommendUnchecked: probPrefer(best, runner-up) ≥ 0.70)
 * abstained. DEVELOPMENT SEEDS ONLY (1–40). Writes docs/scope/v2/DIAGNOSIS.md.
 *
 * For the top-2 pair and for best-vs-manual it records, at the v1 primary budget (16):
 *  m, v   posterior mean / variance of the utility difference (parameter uncertainty)
 *  pred   pairwise PREDICTIVE choice probability sigmoid(m / sqrt(1 + πv/8))   ← what v1 gates on
 *  noiseCap sigmoid(m): the predictive probability with zero parameter uncertainty
 *  post   posterior probability that the utility difference is positive, Φ(m/√v)
 */
fun main(args: Array<String>) {
    Locale.setDefault(Locale.ROOT)
    val out = File(args.firstOrNull() ?: "DIAGNOSIS.md")
    data class Row(val m: Double, val v: Double, val pred: Double, val cap: Double, val post: Double, val trueDu: Double)
    val top2 = ArrayList<Row>()
    val vsManual = ArrayList<Row>()
    val seeds = (1L..40L)
    for (profile in listOf(Profile.P2_CONTEXT_TRADEOFF, Profile.P1_STABLE_ADDITIVE)) for (seed in seeds) {
        val cat = Catalogue("content-1")
        val person = Person(profile, seed)
        val engine = ScopeEngine(cat.schema, ModelConfig.FULL_SCOPE, enabled = true, optedIn = true)
        for (t in 0 until 16) {
            val r = Rng(seed * 7919 + t)
            val act = Protocol.ACTIVITIES[r.int(4)]
            val mode = if (r.double() < 0.5) SocialMode.SOLO else SocialMode.TOGETHER
            val ctx = ContextSnapshot(act, mode)
            val pool = cat.pool(act)
            val i = r.int(pool.size); var j = r.int(pool.size - 1); if (j >= i) j++
            val resp = person.respond(cat.truthOf(pool[i].variantId), cat.truthOf(pool[j].variantId), ctx, t,
                Rng(seed * 31337 + t * 977 + (pool[i].variantId.value + "|" + pool[j].variantId.value).hashCode()))
            engine.update(PairwisePreferenceEvent("d$seed-$t", "p", "s", ctx, pool[i], pool[j], resp, "c", "content-1", ScopeEngine.MODEL_VERSION, 0))
        }
        val post = engine.currentPosterior
        for (act in Protocol.ACTIVITIES) for (mode in SocialMode.entries) {
            val ctx = ContextSnapshot(act, mode)
            val view = cat.viewVariants.getValue(act)
            val ranked = view.sortedByDescending { post.predict(ctx, it).expectedUtility }
            fun row(a: app.smriti.scope.VariantFeatures, b: app.smriti.scope.VariantFeatures): Row {
                val (m, v) = post.difference(ctx, a, b)
                val du = person.utility(cat.truthOf(a.variantId), ctx, 15) - person.utility(cat.truthOf(b.variantId), ctx, 15)
                return Row(m, v, sigmoid(m / sqrt(1 + PI * v / 8)), sigmoid(m), if (v > 0) normalCdf(m / sqrt(v)) else 0.5, du)
            }
            top2 += row(ranked[0], ranked[1])
            val manual = view.first { it.variantId == cat.schema.manualDefaults.getValue(act) }
            if (ranked[0] != manual) vsManual += row(ranked[0], manual)
        }
    }
    fun q(xs: List<Double>, p: Double) = xs.sorted()[((xs.size - 1) * p).toInt()]
    fun f(x: Double) = "%.3f".format(x)
    fun line(name: String, xs: List<Double>) = "| $name | ${f(q(xs, 0.1))} | ${f(q(xs, 0.5))} | ${f(q(xs, 0.9))} | ${f(xs.max())} |"
    val sb = StringBuilder()
    sb.appendLine("# SCOPE v1 confidence-gate diagnosis (development seeds 1–40 only)")
    sb.appendLine()
    sb.appendLine("Generated by `./gradlew :scope:runScopeDiagnosis`. B3-full-SCOPE after 16 comparison opportunities, profiles P2 and P1, all 4 activities × 2 modes per user (${top2.size} contexts). Held-out seeds were not used.")
    sb.appendLine()
    sb.appendLine("## Quantities at the v1 gate: best vs runner-up")
    sb.appendLine()
    sb.appendLine("| quantity | p10 | median | p90 | max |")
    sb.appendLine("|---|---|---|---|---|")
    sb.appendLine(line("posterior mean diff m", top2.map { it.m }))
    sb.appendLine(line("posterior sd of diff √v", top2.map { sqrt(it.v) }))
    sb.appendLine(line("**v1 gate value**: predictive P(choose best)", top2.map { it.pred }))
    sb.appendLine(line("noise cap sigmoid(m) (v = 0)", top2.map { it.cap }))
    sb.appendLine(line("posterior P(Δu > 0) = Φ(m/√v)", top2.map { it.post }))
    sb.appendLine(line("true utility gap best − runner-up", top2.map { it.trueDu }))
    sb.appendLine()
    sb.appendLine("Share of contexts where the v1 gate value reached 0.70: ${f(top2.count { it.pred >= 0.70 }.toDouble() / top2.size)}. Share where even the noise cap sigmoid(m) reached 0.70: ${f(top2.count { it.cap >= 0.70 }.toDouble() / top2.size)}. Share where Φ(m/√v) ≥ 0.70: ${f(top2.count { it.post >= 0.70 }.toDouble() / top2.size)}.")
    sb.appendLine()
    sb.appendLine("## The same quantities for best vs the manual default (when they differ)")
    sb.appendLine()
    sb.appendLine("| quantity | p10 | median | p90 | max |")
    sb.appendLine("|---|---|---|---|---|")
    sb.appendLine(line("posterior mean diff m", vsManual.map { it.m }))
    sb.appendLine(line("posterior sd of diff √v", vsManual.map { sqrt(it.v) }))
    sb.appendLine(line("predictive P(choose best over manual)", vsManual.map { it.pred }))
    sb.appendLine(line("posterior P(best better than manual)", vsManual.map { it.post }))
    sb.appendLine(line("true utility gap best − manual", vsManual.map { it.trueDu }))
    sb.appendLine()
    sb.appendLine("Share of contexts where posterior P(best > manual) ≥ 0.90: ${f(vsManual.count { it.post >= 0.90 }.toDouble() / vsManual.size)}; of those, share where the best truly beats manual: ${f(vsManual.filter { it.post >= 0.90 }.let { s -> if (s.isEmpty()) Double.NaN else s.count { it.trueDu > 0 }.toDouble() / s.size })}.")
    out.parentFile?.mkdirs()
    out.writeText(sb.toString())
    println(sb)
}
