package app.smriti.scope.sim

import java.io.File
import java.util.Locale

/**
 * Runs the frozen protocol on the held-out synthetic users and writes a markdown report.
 * Usage: ./gradlew :scope:runScopeBenchmark   (writes docs/scope/SCOPE_BENCHMARK_RESULTS.md)
 */
fun main(args: Array<String>) {
    Locale.setDefault(Locale.ROOT)
    val outFile = File(args.firstOrNull() ?: "SCOPE_BENCHMARK_RESULTS.md")
    val started = System.currentTimeMillis()
    val sb = StringBuilder()
    fun f(x: Double, d: Int = 3) = if (x.isNaN()) "–" else "%.${d}f".format(x)
    fun pct(x: Double) = "%+.1f%%".format(100 * x)

    // Dev users: only checks the pipeline runs (nothing is tuned on them).
    Simulator.runUser(Profile.P2_CONTEXT_TRADEOFF, Protocol.DEV_SEEDS.first())

    sb.appendLine("# SCOPE v2.1 synthetic benchmark — results")
    sb.appendLine()
    sb.appendLine("Generated by `./gradlew :scope:runScopeBenchmark` from the frozen protocol in `SCOPE_PROTOCOL.md`. Held-out synthetic users ${Protocol.HELDOUT_SEEDS.first()}–${Protocol.HELDOUT_SEEDS.last()} (${Protocol.HELDOUT_SEEDS.size} per profile). **Synthetic simulation only — not evidence of benefit for any person.**")
    sb.appendLine()

    data class GateRow(val profile: Profile, val vs: String, val point: Double, val lo: Double, val hi: Double, val regretRed: Double, val switchOk: Boolean, val go: Boolean)
    val gates = ArrayList<GateRow>()
    val calibAll = ArrayList<Pair<Double, Double>>()
    val diagNames = listOf("B0-fixed", "B1-rules", "B1F-rules+feature-votes", "B2-non-contextual", "B3-full-SCOPE", "B3-VOI")
    val diagRows = LinkedHashMap<Profile, Map<String, Double>>()

    for (profile in Profile.entries) {
        val perUser = Protocol.HELDOUT_SEEDS.map { Simulator.runUser(profile, it) }
        val names = perUser.first().keys.toList()
        diagRows[profile] = diagNames.associateWith { n -> perUser.map { it.getValue(n).getValue(Protocol.PRIMARY_CHECKPOINT).regretNoAbstain }.average() }
        sb.appendLine("## ${profile.label}")
        sb.appendLine()
        sb.appendLine("At the primary checkpoint (${Protocol.PRIMARY_CHECKPOINT} comparison opportunities). Means over ${perUser.size} held-out users. Lower CE/regret is better.")
        sb.appendLine()
        sb.appendLine("| Controller | held-out CE | CE unseen pairs | agreement | norm. regret | abstain | preq. log loss | preq. Brier | answered L/R | asked | switch rate |")
        sb.appendLine("|---|---|---|---|---|---|---|---|---|---|---|")
        for (n in names) {
            val ms = perUser.map { it.getValue(n).getValue(Protocol.PRIMARY_CHECKPOINT) }
            fun avg(sel: (Metrics) -> Double) = ms.map(sel).filterNot { it.isNaN() }.let { if (it.isEmpty()) Double.NaN else it.average() }
            sb.appendLine("| $n | ${f(avg { it.heldoutCE })} | ${f(avg { it.heldoutCEUnseen })} | ${f(avg { it.agreement })} | ${f(avg { it.normRegret })} | ${f(avg { it.abstainRate })} | ${f(avg { it.prequentialLogLoss })} | ${f(avg { it.prequentialBrier })} | ${f(avg { it.labelledSoFar.toDouble() }, 1)} | ${f(avg { it.asked.toDouble() }, 1)} | ${f(avg { it.switchRate })} |")
            if (n == "B3-full-SCOPE") calibAll += ms.flatMap { it.calibration }
        }
        sb.appendLine()
        sb.appendLine("Held-out CE by budget (learning curve):")
        sb.appendLine()
        sb.appendLine("| Controller | " + Protocol.CHECKPOINTS.joinToString(" | ") { "@$it" } + " |")
        sb.appendLine("|---|" + Protocol.CHECKPOINTS.joinToString("") { "---|" })
        for (n in names) {
            sb.appendLine("| $n | " + Protocol.CHECKPOINTS.joinToString(" | ") { cp -> f(perUser.map { it.getValue(n).getValue(cp).heldoutCE }.average()) } + " |")
        }
        sb.appendLine()
        sb.appendLine("Paired bootstrap (95% CI) of relative held-out CE improvement of **B3-full-SCOPE** over each comparator, and gate result:")
        sb.appendLine()
        sb.appendLine("| vs | rel. CE improvement | 95% CI | regret reduction | switching non-inferior | GO? |")
        sb.appendLine("|---|---|---|---|---|---|")
        val b3 = perUser.map { it.getValue("B3-full-SCOPE").getValue(Protocol.PRIMARY_CHECKPOINT) }
        for (cmp in listOf("B1-rules", "B1F-rules+feature-votes", "B2-non-contextual")) {
            val base = perUser.map { it.getValue(cmp).getValue(Protocol.PRIMARY_CHECKPOINT) }
            val (pt, lo, hi) = Simulator.pairedBootstrap(base.map { it.heldoutCE }.toDoubleArray(), b3.map { it.heldoutCE }.toDoubleArray())
            val rb = base.map { it.normRegret }.average()
            val r3 = b3.map { it.normRegret }.average()
            val regretRed = if (rb > 0) (rb - r3) / rb else 0.0
            val switchOk = b3.map { it.switchRate }.average() <= base.map { it.switchRate }.average() + 0.05
            val go = pt >= 0.05 && lo > 0 && regretRed >= 0.10 && switchOk
            gates += GateRow(profile, cmp, pt, lo, hi, regretRed, switchOk, go)
            sb.appendLine("| $cmp | ${pct(pt)} | [${pct(lo)}, ${pct(hi)}] | ${pct(regretRed)} | ${if (switchOk) "yes" else "**no**"} | ${if (go) "**GO**" else "no-go"} |")
        }
        sb.appendLine()
    }

    sb.appendLine("## Post-hoc diagnostic (added after the definitive run; NOT part of the pre-registered gate)")
    sb.appendLine()
    sb.appendLine("Normalised regret if each controller always proposed its top-ranked variant, ignoring its abstention rule, at the primary checkpoint. This separates ranking quality from the conservative proposal threshold. It must not be read as a verdict.")
    sb.appendLine()
    sb.appendLine("| Profile | " + diagNames.joinToString(" | ") + " |")
    sb.appendLine("|---|" + diagNames.joinToString("") { "---|" })
    for ((p, row) in diagRows) sb.appendLine("| ${p.label} | " + diagNames.joinToString(" | ") { f(row.getValue(it)) } + " |")
    sb.appendLine()

    sb.appendLine("## Calibration of B3-full-SCOPE (all profiles, primary checkpoint, held-out pairs)")
    sb.appendLine()
    sb.appendLine("| predicted P(left) bucket | n | mean predicted | mean true p* |")
    sb.appendLine("|---|---|---|---|")
    for (b in 0 until 5) {
        val lo = b * 0.2; val hi = lo + 0.2
        val inB = calibAll.filter { it.first >= lo && (it.first < hi || (b == 4 && it.first <= 1.0)) }
        if (inB.isNotEmpty()) sb.appendLine("| ${f(lo, 1)}–${f(hi, 1)} | ${inB.size} | ${f(inB.map { it.first }.average())} | ${f(inB.map { it.second }.average())} |")
    }
    sb.appendLine()

    sb.appendLine("## Pre-registered verdict")
    sb.appendLine()
    val p2Gate = gates.filter { it.profile == Profile.P2_CONTEXT_TRADEOFF && it.vs in setOf("B1-rules", "B1F-rules+feature-votes") }
    val p2Pass = p2Gate.size == 2 && p2Gate.all { it.go }
    val harmful = gates.filter { it.profile in setOf(Profile.P1_STABLE_ADDITIVE, Profile.P8_NO_CONTEXT_WEAK, Profile.P9_PARTIAL_METADATA) && it.vs in setOf("B1-rules", "B1F-rules+feature-votes") && it.hi < 0 }
    sb.appendLine("| Profile | vs B1 | vs B1F | vs B2 |")
    sb.appendLine("|---|---|---|---|")
    for (p in Profile.entries) {
        fun cell(vs: String) = gates.first { it.profile == p && it.vs == vs }.let { "${if (it.go) "GO" else "no-go"} (${pct(it.point)}, CI [${pct(it.lo)}, ${pct(it.hi)}])" }
        sb.appendLine("| ${p.label} | ${cell("B1-rules")} | ${cell("B1F-rules+feature-votes")} | ${cell("B2-non-contextual")} |")
    }
    sb.appendLine()
    val verdict = p2Pass && harmful.isEmpty()
    sb.appendLine(
        if (verdict) "**Pre-registered criterion met:** full SCOPE passed the gate against both rule baselines on P2 and did not lose significantly to them on P1, P8 or P9. This is a statement about these synthetic assumptions only; SCOPE remains disabled by default."
        else "**Pre-registered criterion NOT met.** " +
            (if (!p2Pass) "Full SCOPE did not pass the gate against both rule baselines on P2. " else "") +
            (if (harmful.isNotEmpty()) "It lost significantly to a rule baseline on: ${harmful.joinToString { it.profile.label + " vs " + it.vs }}. " else "") +
            "Per the annex, SCOPE must not be described as better than rules and stays disabled."
    )
    sb.appendLine()
    sb.appendLine("Runtime: ${(System.currentTimeMillis() - started) / 1000} s.")
    outFile.parentFile?.mkdirs()
    outFile.writeText(sb.toString())
    println(sb)
}
