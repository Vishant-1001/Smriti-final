package app.smriti.fit

import androidx.compose.ui.unit.Density
import androidx.compose.ui.unit.sp
import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.annotation.Config
import java.io.File
import java.util.Locale

/**
 * Records how Compose converts sp to dp for each total font scale SMRITI can produce
 * (system scale × in-app text level), on SDK 34 where Android 14's non-linear font scaling applies.
 * The app builds `Density(density, fontScale)` itself (Theme.kt); this measures what that yields.
 *
 * Writes fit/src/main/resources/app/smriti/fit/font_scale_sdk34.tsv.
 */
@RunWith(AndroidJUnit4::class)
@Config(sdk = [34])
class FontScaleTableTest {
    @Test
    fun recordConversion() {
        val system = listOf(0.85, 1.0, 1.15, 1.3, 1.5, 1.8, 2.0)
        val levels = listOf(1.0, 1.2, 1.4)
        val sizes = listOf(15, 17, 18, 19, 22, 26, 28, 32)
        val lines = mutableListOf("# total_font_scale\tsp\tdp   (Compose Density(2f, scale) on SDK 34; generated by FontScaleTableTest)")
        var nonLinear = false
        for (s in system) for (l in levels) {
            val scale = (s * l).toFloat()
            val d = Density(2f, scale)
            for (sp in sizes) {
                val dp = with(d) { sp.sp.toDp().value }
                if (kotlin.math.abs(dp - sp * scale) > 0.05) nonLinear = true
                lines += "${"%.4f".format(Locale.ROOT, scale)}\t$sp\t${"%.4f".format(Locale.ROOT, dp)}"
            }
        }
        File("../fit/src/main/resources/app/smriti/fit/font_scale_sdk34.tsv").writeText(lines.joinToString("\n", postfix = "\n"))
        println(lines.take(40).joinToString("\n"))
        assertTrue(lines.size > 100)
        println("non-linear: $nonLinear")
    }
}
