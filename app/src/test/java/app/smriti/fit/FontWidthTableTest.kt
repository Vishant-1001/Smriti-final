package app.smriti.fit

import android.graphics.Paint
import androidx.core.content.res.ResourcesCompat
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import app.smriti.R
import app.smriti.fit.sim.AwtMeasurer
import app.smriti.fit.sim.Content
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode
import java.io.File
import java.util.Locale

/**
 * Measures every SMRITI string and every word in it with Android's own text stack (Paint/minikin
 * with HarfBuzz, Robolectric native graphics) using the app's bundled bold fonts. It writes:
 *  - fit-bench/src/main/resources/app/smriti/fit/android_widths.tsv: width in em per (language, text);
 *  - docs/flagship/FIT_FONT_CHECK.md: how far the JVM (AWT) measurement is from Android's.
 *
 * Run: ./gradlew :app:testDebugUnitTest --tests app.smriti.fit.FontWidthTableTest
 */
@RunWith(AndroidJUnit4::class)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
@Config(sdk = [34])
class FontWidthTableTest {
    @Test
    fun measureAllStrings() {
        // Writes committed result files; runs only when asked: -Dfit.validation=true
        assumeTrue(System.getProperty("fit.validation") == "true")
        val ctx = ApplicationProvider.getApplicationContext<android.content.Context>()
        val res = File("src/main/res")
        val content = Content(res)
        val awt = AwtMeasurer(res)
        val paints = mapOf(
            Lang.TAMIL to Paint().apply { typeface = ResourcesCompat.getFont(ctx, R.font.noto_sans_tamil_bold); textSize = 100f; isAntiAlias = true },
            Lang.ENGLISH to Paint().apply { typeface = ResourcesCompat.getFont(ctx, R.font.noto_sans_bold); textSize = 100f; isAntiAlias = true },
        )
        val rows = sortedMapOf<String, Double>()
        val ratios = mutableMapOf(Lang.TAMIL to mutableListOf<Double>(), Lang.ENGLISH to mutableListOf())
        for (lang in Lang.entries) {
            val texts = (if (lang == Lang.TAMIL) content.ta else content.en).values
            val all = texts.flatMap { t -> listOf(t) + t.split(' ').filter { it.isNotEmpty() } } +
                listOf("பட்டியல் 2/5", "List 2/5")
            for (t in all.toSet()) {
                if (t.isBlank() || '\n' in t || '\t' in t) continue
                val android = paints.getValue(lang).measureText(t) / 100.0
                rows["${lang.name}\t$t"] = android
                val a = awt.widthDp(t, lang, 100.0) / 100.0
                if (android > 0.3) ratios.getValue(lang) += a / android
            }
        }
        val out = File("../fit-bench/src/main/resources/app/smriti/fit/android_widths.tsv")
        out.parentFile.mkdirs()
        out.writeText(
            "# Width in em of each SMRITI string and word, measured with Android Paint (Robolectric native graphics, SDK 34)\n" +
                "# using the app's bundled bold Noto fonts. Generated by app/src/test/java/app/smriti/fit/FontWidthTableTest.kt\n" +
                rows.entries.joinToString("") { (k, v) -> "$k\t${"%.5f".format(Locale.ROOT, v)}\n" },
        )
        fun q(l: List<Double>, p: Double) = l.sorted()[((l.size - 1) * p).toInt()]
        val report = buildString {
            appendLine("# SMRITI Fit: JVM (AWT) text widths vs Android's text stack")
            appendLine()
            appendLine("Ratio = AWT width / Android Paint width for the same string and bold font (1.00 = identical). Strings and their words, both languages.")
            appendLine()
            appendLine("| Language | n | median | p5 | p95 | min | max |")
            appendLine("|---|---|---|---|---|---|---|")
            for ((lang, l) in ratios) {
                appendLine("| $lang | ${l.size} | ${f(q(l, 0.5))} | ${f(q(l, 0.05))} | ${f(q(l, 0.95))} | ${f(l.min())} | ${f(l.max())} |")
            }
            appendLine()
            appendLine("The table of Android widths is written to `fit-bench/src/main/resources/app/smriti/fit/android_widths.tsv`.")
        }
        File("../docs/flagship/FIT_FONT_CHECK.md").writeText(report)
        println(report)
        assertTrue(rows.size > 500)
    }

    private fun f(x: Double) = "%.3f".format(Locale.ROOT, x)
}
